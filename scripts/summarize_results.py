"""Build the report's tables from the committed ``results/`` folder.

    python scripts/summarize_results.py            # writes results/summary.md

Every number in the report should trace back to a file read here.
"""

from __future__ import annotations

import json
from pathlib import Path

R = Path("results")


def load(path: Path):
    return json.loads(path.read_text()) if path.exists() else None


def evals(run: Path) -> list[dict]:
    path = run / "metrics.jsonl"
    if not path.exists():
        return []
    return [r for r in map(json.loads, path.read_text().splitlines()) if r.get("kind") == "eval"]


def gen_stats(path: Path) -> str:
    rows = load(path)
    if not rows:
        return "n/a"
    n_len = sum(r["finish_reason"] == "length" for r in rows)
    words = sum(len(r["output"].split()) for r in rows) / len(rows)
    return f"{len(rows)} rows, {n_len} hit max tokens, {words:.0f} words on average"


def judge_row(summary: dict, q: str = "verdict") -> str:
    d = summary[q]
    w, l, t, u = d["wins"], d["losses"], d["ties"], d["unknown"]
    ex = d["win_rate_excluding_ties"]
    half = d["win_rate_ties_half"]
    return (f"| {summary['candidate']} vs {summary['baseline']} | {summary['n_pairs']} | {w} | {l} | {t} | {u} | "
            f"{summary['n_failed']} | {ex:.3f} | {half:.3f} |" if ex is not None else "| n/a |")


def main() -> None:
    out = ["# PA2 results summary", "", "Generated by `scripts/summarize_results.py` from `results/`.", ""]

    sft = load(R / "sft" / "summary.json")
    if sft:
        ev = evals(R / "sft")
        out += ["## SFT", "", f"- best step {sft['best_step']} of {sft['total_steps']}, best validation loss {sft['best_val_loss']:.4f}",
                f"- validation loss by step: " + ", ".join(f"{e['step']}: {e['val_loss']:.4f}" for e in ev), ""]

    for run, label in (("dpo_hh", "DPO HH-RLHF"), ("dpo_uf", "DPO UltraFeedback")):
        s = load(R / run / "summary.json")
        if not s:
            continue
        ev = evals(R / run)
        out += [f"## {label}", "",
                f"- best step {s['best_step']} of {s['total_steps']}: validation reward accuracy {s['best_val_reward_acc']:.3f}, "
                f"margin {s['best_val_reward_margin']:.4f}",
                "", "| step | val loss | reward acc | margin | chosen reward | rejected reward |", "|---|---|---|---|---|---|"]
        out += [f"| {e['step']} | {e['val_loss']:.4f} | {e['val_reward_acc']:.3f} | {e['val_reward_margin']:.4f} | "
                f"{e['val_chosen_reward']:.4f} | {e['val_rejected_reward']:.4f} |" for e in ev]
        out.append("")

    out += ["## Generations", ""]
    for f in sorted((R / "eval_generations").glob("*__*.json")):
        if not f.name.endswith(".settings.json"):
            out.append(f"- `{f.name}`: {gen_stats(f)}")
    for f in sorted((R / "baseline").glob("*/*.json")):
        if not f.name.endswith(".settings.json"):
            out.append(f"- baseline `{f.parent.name}/{f.name}`: {gen_stats(f)}")
    out.append("")

    judged = sorted((R / "judgments").glob("*_summary.json"))
    if judged:
        out += ["## DPO vs SFT (blind pairwise judge)", "",
                "| comparison | pairs | DPO wins | SFT wins | ties | unknown | failed | win rate excl. ties | win rate, ties = 1/2 |",
                "|---|---|---|---|---|---|---|---|---|"]
        for f in judged:
            out.append(judge_row(load(f)))
        out.append("")
        for f in judged:
            s = load(f)
            cats = s["verdict"]["by_category"]
            if cats:
                out += [f"### {s['candidate']} vs {s['baseline']} by category ({s['judge_model']}, mode {s['mode']})", "",
                        "| category | DPO wins | SFT wins | ties | unknown |", "|---|---|---|---|---|"]
                out += [f"| {c} | {d['wins']} | {d['losses']} | {d['ties']} | {d['unknown']} |" for c, d in cats.items()]
                out.append("")

    persona = sorted((R / "persona" / "judgments").glob("*_summary.json"), key=lambda f: int(f.name.split("_v")[1].split("_")[0]))
    if persona:
        out += ["## Persona LoRA-DPO vs untuned SmolLM2 (blind pairwise judge)", "",
                "| variant | lr | beta | loss | held-out acc | margin | style W-L-T | helpfulness W-L-T | safety W-L-T |",
                "|---|---|---|---|---|---|---|---|---|"]
        for f in persona:
            s = load(f)
            run = s["candidate"]
            folder = "lora_dpo" if run == "lora_dpo_v1" else run  # v1 was trained before the sweep naming
            summ = load(R / "persona" / folder / "summary.json")
            cfg, fe = summ["config"], summ["final_eval"]
            cell = lambda q: f"{s[q]['wins']}-{s[q]['losses']}-{s[q]['ties']}"
            out.append(f"| {run} | {cfg['lr']} | {cfg['beta']} | {'+'.join(cfg.get('loss_type', ['sigmoid']))} | "
                       f"{fe['eval_rewards/accuracies']:.2f} | {fe['eval_rewards/margins']:.3f} | "
                       f"{cell('style')} | {cell('helpfulness')} | {cell('safety')} |")
        out.append("")

    (R / "summary.md").write_text("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
